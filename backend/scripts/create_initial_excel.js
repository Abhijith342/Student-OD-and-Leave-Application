function generateExcel() {
  const lines = rawCSVData.trim().split('\n');
  const headers = lines[0].split(',');
  const rows = lines.slice(1).map(line => {
    const values = line.split(',');
    const obj = {};
    headers.forEach((h, idx) => {
      obj[h.trim()] = values[idx] ? values[idx].trim() : '';
    });
    return obj;
  });

  const worksheet = XLSX.utils.json_to_sheet(rows, { header: headers });
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Students');

  const assetsDir = path.resolve(__dirname, '../src/assets');
  const publicDir = path.resolve(__dirname, '../../frontend/public');

  if (!fs.existsSync(assetsDir)) fs.mkdirSync(assetsDir, { recursive: true });
  if (!fs.existsSync(publicDir)) fs.mkdirSync(publicDir, { recursive: true });

  const backendExcelPath = path.join(assetsDir, 'initial_students.xlsx');
  const frontendTemplatePath = path.join(publicDir, 'Student_Import_Template.xlsx');

  XLSX.writeFile(workbook, backendExcelPath);
  XLSX.writeFile(workbook, frontendTemplatePath);

  console.log(`✅ Excel files created successfully:`);
  console.log(`   - Backend dataset: ${backendExcelPath}`);
  console.log(`   - Frontend Template: ${frontendTemplatePath}`);
}

generateExcel();
